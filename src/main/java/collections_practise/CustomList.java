package collections_practise;

/**
 * Интерфейс для работы со списками.
 * Определяет основные операции для работы с коллекцией элементов с возможностью доступа по индексу.
 *
 * @param <A> тип элементов в списке
 */
public interface CustomList<A> {

  /**
   * Добавляет указанный элемент в список.
   *
   * @param elem элемент для добавления в список
   * @throws IllegalArgumentException если переданный элемент равен null
   */
  void add(A elem);

  /**
   * Удаляет элемент по указанному индексу из списка.
   * Все последующие элементы сдвигаются влево.
   *
   * @param index индекс удаляемого элемента
   * @return удаленный элемент
   * @throws IndexOutOfBoundsException если индекс выходит за границы списка
   */
  A remove(int index);

  /**
   * Возвращает элемент по указанному индексу в списке.
   *
   * @param index индекс запрашиваемого элемента
   * @return элемент по указанному индексу
   * @throws IndexOutOfBoundsException если индекс выходит за границы списка
   */
  A get(int index);

  /**
   * Возвращает количество элементов в списке.
   *
   * @return количество элементов в списке
   */
  int size();

  /**
   * Проверяет, пуст ли список.
   *
   * @return true если список не содержит элементов, иначе false
   */
  boolean isEmpty();
}